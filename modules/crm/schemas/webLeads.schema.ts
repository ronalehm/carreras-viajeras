import { z } from "zod";
import { INQUIRY_DESTINATION_IDS } from "@/lib/inquiryDestinations";
import { phoneSchema } from "./leads.schema";

const NAME_MESSAGE = "Escribe tu nombre (2 a 80 caracteres).";
const EMAIL_MESSAGE = "Escribe un correo válido.";
const DESTINATION_MESSAGE = "Elige un destino.";
const CONSENT_MESSAGE = "Necesitamos tu autorización para guardar tus datos.";
const SUBMISSION_MESSAGE = "Recarga la página e inténtalo de nuevo.";

// Public landing form. Input: the strings of Object.fromEntries(formData). z.object drops unknown
// keys (source, stage, ownerUserId, consentVersion…): they never come from the form. The honeypot
// (website) and the 16 KiB limit are checked by the action before this schema.
export const webLeadFormSchema = z
  .object({
    name: z.string({ error: NAME_MESSAGE }).trim().min(2, NAME_MESSAGE).max(80, NAME_MESSAGE),
    email: z
      .string({ error: EMAIL_MESSAGE })
      .trim()
      .toLowerCase()
      .pipe(z.email({ error: EMAIL_MESSAGE }).max(150, EMAIL_MESSAGE)),
    phone: phoneSchema,
    destination: z.enum(INQUIRY_DESTINATION_IDS, { error: DESTINATION_MESSAGE }),
    consent: z.literal("on", { error: CONSENT_MESSAGE }),
    // UUID generated by the browser on submit: the idempotency key of the lead.
    submissionId: z.uuid({ error: SUBMISSION_MESSAGE }),
    // Field injected by the Turnstile widget; an empty token is rejected by the verification.
    "cf-turnstile-response": z.string({ error: SUBMISSION_MESSAGE }).max(2048, SUBMISSION_MESSAGE).default(""),
  })
  .transform(({ name, email, phone, destination, submissionId, "cf-turnstile-response": turnstileToken }) => ({
    fullName: name,
    email,
    phone,
    destination,
    submissionId,
    turnstileToken,
  }));
