import { z } from "zod";
import { normalizeCampaignCode, normalizeReferral, normalizeUtm } from "../utils/leadAttribution";
import { phoneSchema } from "./leads.schema";

const NAME_MESSAGE = "Escribe tu nombre (2 a 80 caracteres).";
const EMAIL_MESSAGE = "Escribe un correo válido.";
const DESTINATION_MESSAGE = "Elige la carrera.";

// Attribution parameter (hidden field copied from the URL): normalized or null, never an error.
const attribution = (normalize: (value: string | null | undefined) => string | null) =>
  z.string().max(200).nullish().catch(null).transform(normalize);

// Public web form (race registration and /contacto). Input: the strings of
// Object.fromEntries(formData). z.object drops unknown keys (source, stage, channel, campaignId,
// ownerUserId, consentVersion, price…): they never come from the form. The honeypot (website) and
// the 16 KiB limit are checked by the action first. destination is a published trip slug or an
// INQUIRY_DESTINATIONS id: createWebLead resolves it ("unknown_trip" if it is not published).
export const webLeadFormSchema = z
  .object({
    name: z.string({ error: NAME_MESSAGE }).trim().min(2, NAME_MESSAGE).max(80, NAME_MESSAGE),
    email: z
      .string({ error: EMAIL_MESSAGE })
      .trim()
      .toLowerCase()
      .pipe(z.email({ error: EMAIL_MESSAGE }).max(150, EMAIL_MESSAGE)),
    phone: phoneSchema,
    destination: z
      .string({ error: DESTINATION_MESSAGE })
      .regex(/^[a-z0-9]+(-[a-z0-9]+)*$/, DESTINATION_MESSAGE)
      .max(80, DESTINATION_MESSAGE),
    consent: z.literal("on", { error: "Necesitamos tu autorización para guardar tus datos." }),
    // Independent promotions checkbox: "on" only when checked; anything else is false, never an error.
    marketing: z.literal("on").optional().catch(undefined),
    // Generated by the browser on submit: the idempotency key of this submission.
    submissionId: z.uuid(),
    // Injected by the Turnstile widget; missing → "" (verified, and rejected, by the service).
    "cf-turnstile-response": z.string().max(2048).default(""),
    c: attribution(normalizeCampaignCode),
    utm_source: attribution(normalizeUtm),
    utm_medium: attribution(normalizeUtm),
    utm_campaign: attribution(normalizeUtm),
    ref: attribution(normalizeReferral),
  })
  .transform((value) => ({
    fullName: value.name,
    email: value.email,
    phone: value.phone,
    destination: value.destination,
    marketingOptIn: value.marketing === "on",
    submissionId: value.submissionId,
    turnstileToken: value["cf-turnstile-response"],
    campaignCode: value.c,
    utmSource: value.utm_source,
    utmMedium: value.utm_medium,
    utmCampaign: value.utm_campaign,
    referredBy: value.ref,
  }));
