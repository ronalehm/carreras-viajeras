import { z } from "zod";
import { INQUIRY_DESTINATION_IDS } from "@/lib/inquiryDestinations";
import { phoneSchema } from "./leads.schema";

const NAME_MESSAGE = "Escribe tu nombre (2 a 80 caracteres).";
const EMAIL_MESSAGE = "Escribe un correo válido.";

// Public web form (landing /contacto). Input: the strings of Object.fromEntries(formData).
// z.object drops unknown keys (source, stage, ownerUserId, consentVersion…): they never come from
// the form. The honeypot (website) and the 16 KiB limit are checked by the action first.
export const webLeadFormSchema = z
  .object({
    name: z.string({ error: NAME_MESSAGE }).trim().min(2, NAME_MESSAGE).max(80, NAME_MESSAGE),
    email: z
      .string({ error: EMAIL_MESSAGE })
      .trim()
      .toLowerCase()
      .pipe(z.email({ error: EMAIL_MESSAGE }).max(150, EMAIL_MESSAGE)),
    phone: phoneSchema,
    destination: z.enum(INQUIRY_DESTINATION_IDS, { error: "Elige un destino." }),
    consent: z.literal("on", { error: "Necesitamos tu autorización para guardar tus datos." }),
    // Generated by the browser on submit: the idempotency key of this submission.
    submissionId: z.uuid(),
    // Injected by the Turnstile widget; missing → "" (verified, and rejected, by the service).
    "cf-turnstile-response": z.string().max(2048).default(""),
  })
  .transform(({ name, email, phone, destination, submissionId, "cf-turnstile-response": turnstileToken }) => ({
    fullName: name,
    email,
    phone,
    destination,
    submissionId,
    turnstileToken,
  }));
